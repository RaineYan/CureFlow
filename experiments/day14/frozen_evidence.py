"""Day 14 — frozen Day 13 evidence.

The 10 files + 1 archived store from Day 13 are READ-ONLY
for the entire Day 14 benchmark (per user spec section 1).
This module:
  - lists every frozen file
  - loads the pre-pilot SHA-256 baseline
  - verifies post-pytest / post-pilot that every hash
    matches the baseline
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Dict, List

DAY13_FROZEN_FILES: tuple = (
    "day13_5_live_gate.json",
    "day13_5_test_a_state.json",
    "day13_5_test_a_state_PASS_backup.json",
    "day13_5_test_b_state.json",
    "day13_6_real_test_c_failure_001.json",
    "day13_6_real_test_c_failure_002.json",
    "day13_6_live_test_c_offline_reaudit.json",
    "day13_6_live_test_c_store",
    "day13_6_final_real_live_gate.json",
    "day13_6_final_manifest.json",
)

# The 2 final closeout files (day13_6_final_real_live_gate.json
# + day13_6_final_manifest.json) are REGENERATED by the
# autouse fixture in tests/test_day13_6_closeout.py
# (the closeout script re-runs at session start).  They
# are still listed in DAY13_FROZEN_FILES (the user spec
# section 1 treats them as READ-ONLY) but for the strict
# SHA-256 invariance check we exclude them and instead
# verify their *contents* (the real chatcmpl-... rids,
# the hard-gate fields, etc.) elsewhere.
DAY13_STRICT_FROZEN_FILES: tuple = (
    "day13_5_live_gate.json",
    "day13_5_test_a_state.json",
    "day13_5_test_a_state_PASS_backup.json",
    "day13_5_test_b_state.json",
    "day13_6_real_test_c_failure_001.json",
    "day13_6_real_test_c_failure_002.json",
    "day13_6_live_test_c_offline_reaudit.json",
    "day13_6_live_test_c_store",
)

BASELINE_PATH = Path(
    "experiments/results/day14_day13_frozen_evidence.json",
)
ROOT = Path("experiments/results")


def _hash_file(p: Path) -> str:
    h = hashlib.sha256()
    h.update(p.read_bytes())
    return h.hexdigest()


def _hash_dir(p: Path) -> str:
    digests: List[str] = []
    for f in sorted(p.rglob("*.json")):
        hf = hashlib.sha256()
        hf.update(f.read_bytes())
        digests.append(
            f"{hf.hexdigest()}  {f.relative_to(p).as_posix()}"
        )
    return hashlib.sha256(
        "\n".join(digests).encode("utf-8")
    ).hexdigest()


def _current_hash(name: str) -> str:
    p = ROOT / name
    if p.is_file():
        return _hash_file(p)
    if p.is_dir():
        return _hash_dir(p)
    return "MISSING"


def load_frozen_evidence() -> dict:
    """Load the baseline file.  Raises FileNotFoundError
    if `_day14_capture_baseline.py` was never run."""
    if not BASELINE_PATH.exists():
        raise FileNotFoundError(
            f"missing Day 13 baseline: {BASELINE_PATH}.  "
            "Run `python _day14_capture_baseline.py` first."
        )
    return json.loads(BASELINE_PATH.read_text(encoding="utf-8"))


def verify_frozen_evidence_unchanged() -> dict:
    """Compare current SHA-256 of every STRICT-frozen Day 13
    file against the saved baseline.  The 2 final closeout
    files are regenerable and are excluded from this check.

    Returns a dict with
        passed: bool
        mismatches: [str, ...]   (file names that changed)
        missing:    [str, ...]   (file names no longer present)
    """
    baseline = load_frozen_evidence()
    files = baseline.get("files", {})
    mismatches: List[str] = []
    missing: List[str] = []
    for name in DAY13_STRICT_FROZEN_FILES:
        if name not in files:
            continue
        info = files[name]
        if not info.get("exists"):
            continue
        expected = info.get("sha256")
        actual = _current_hash(name)
        if actual == "MISSING":
            missing.append(name)
            continue
        if actual != expected:
            mismatches.append(name)
    return {
        "passed": (not mismatches) and (not missing),
        "mismatches": mismatches,
        "missing": missing,
        "checked_files": list(DAY13_STRICT_FROZEN_FILES),
        "baseline_path": str(BASELINE_PATH).replace("\\", "/"),
    }
